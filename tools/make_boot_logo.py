"""Convert the adopted transparent logo to black-matted, indexed boot data.

Requires ImageMagick convert only when regenerating the checked-in header.
Packets: low seven bits + 1 = length; bit 7 selects repeated index (one
following byte) or literal indices (length following bytes).
"""
import argparse
import hashlib
from pathlib import Path
import subprocess
import tempfile


def pack(indices):
    out = bytearray()
    i = 0
    while i < len(indices):
        j = i + 1
        while j < len(indices) and indices[j] == indices[i] and j-i < 128:
            j += 1
        if j-i >= 3:
            out.extend((0x80 | (j-i-1), indices[i]))
            i = j
        else:
            start = i
            i += 1
            while i < len(indices) and i-start < 128:
                if i+2 < len(indices) and indices[i] == indices[i+1] == indices[i+2]:
                    break
                i += 1
            out.append(i-start-1)
            out.extend(indices[start:i])
    return out


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('source', type=Path)
    p.add_argument('header', type=Path)
    p.add_argument('--preview', type=Path)
    args = p.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        ppm = Path(tmp)/'logo.ppm'
        subprocess.run(['convert', str(args.source), '-background', 'black',
                        '-alpha', 'remove', '-alpha', 'off', '-resize', '360x',
                        '-dither', 'None', '-colors', '128', '-depth', '8', str(ppm)], check=True)
        magic, dimensions, maximum, rgb = ppm.read_bytes().split(b'\n', 3)
        assert magic == b'P6' and maximum == b'255'
        w, h = map(int, dimensions.split())
        assert w <= 640 and h <= 480 and len(rgb) == w*h*3
        if args.preview:
            subprocess.run(['convert', str(ppm), str(args.preview)], check=True)
    pixels = [rgb[i:i+3] for i in range(0, len(rgb), 3)]
    palette = list(dict.fromkeys(pixels))
    assert len(palette) <= 256
    indices = bytes(palette.index(c) for c in pixels)
    packed = pack(indices)
    fnv = 2166136261
    for c in rgb:
        fnv = ((fnv ^ c) * 16777619) & 0xffffffff
    lines = [
        "// SPDX-License-Identifier: CC-BY-4.0",
        '/* Generated by tools/make_boot_logo.py; do not edit. */',
        '/* Source SHA256: '+hashlib.sha256(args.source.read_bytes()).hexdigest()+' */',
        '/* RGB SHA256: '+hashlib.sha256(rgb).hexdigest()+' */',
        '#ifndef TARUGX_BOOT_LOGO_DATA_H', '#define TARUGX_BOOT_LOGO_DATA_H',
        '#include <stdint.h>', f'#define TGX_LOGO_WIDTH {w}u',
        f'#define TGX_LOGO_HEIGHT {h}u', f'#define TGX_LOGO_RGB_FNV 0x{fnv:08x}u',
        'static const uint32_t tgx_logo_palette[] = {',
        ','.join('0x'+c.hex()+'u' for c in palette), '};',
        'static const uint8_t tgx_logo_data[] = {']
    for i in range(0, len(packed), 20):
        lines.append(','.join(f'0x{c:02x}' for c in packed[i:i+20])+',')
    lines.extend(['};', '#endif', ''])
    args.header.write_text('\n'.join(lines))
    print(f'{w}x{h}, {len(palette)} colors, {len(packed)} packet bytes, RGB FNV {fnv:08x}')


if __name__ == '__main__':
    main()
